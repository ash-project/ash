defmodule Ash.Page.Keyset do
  @moduledoc """
  A page of results from `keyset` based pagination.

  The results are generated with a `keyset` metadata,
  which can be used to fetch the next/previous pages.

  A keyset is the sort values of a record. How it is encoded depends on whether
  `config :ash, :keyset_signing_secret` is set:

  * With a secret, the values are encoded with `:erlang.term_to_binary/1` and signed
    with an HMAC. Ash only decodes keysets whose signature is valid, so every keyset it
    decodes was generated by this application.
  * Without a secret, the values are dumped with `Ash.Type.dump_to_embedded/3` and
    encoded as JSON. Decoding JSON can only produce plain data, never structs,
    functions or atoms, and each value is cast back with `Ash.Type.coerce/3`, the same
    way values in a client-supplied filter are cast. A record sorted by values that
    can't be encoded as JSON has no keyset.
  """

  # Upper bound on the size (in bytes) of an unsigned keyset. Keysets
  # legitimately encode only the sort values of a single record, so this is
  # generous; it exists purely to bound the work done decoding a hostile one.
  # Configurable via `config :ash, max_keyset_byte_size: ...`.
  @default_max_keyset_byte_size 10_240

  @derive {Inspect, only: [:results, :count, :before, :after, :more?]}
  defstruct [:results, :count, :before, :after, :limit, :rerun, :more?]

  @type t :: %__MODULE__{
          results: [Ash.Resource.Record.t()],
          count: non_neg_integer(),
          before: binary() | nil,
          after: binary() | nil,
          limit: pos_integer(),
          more?: boolean(),
          rerun: {Ash.Query.t(), Keyword.t()}
        }

  @type page_opts_type :: :non_neg_integer | :pos_integer | :any | :boolean
  @type page_opts_opts :: [type: page_opts_type(), doc: String.t()]
  @type page_opts :: [
          before: page_opts_opts(),
          after: page_opts_opts(),
          limit: page_opts_opts(),
          filter: page_opts_opts(),
          count: page_opts_opts()
        ]

  @page_opts [
    before: [
      type: :string,
      doc: "Get records that appear before the provided keyset (mutually exclusive with `after`)"
    ],
    after: [
      type: :string,
      doc: "Get records that appear after the provided keyset (mutually exclusive with `before`)"
    ],
    limit: [
      type: :pos_integer,
      doc: "How many records to include in the page"
    ],
    filter: [
      type: :any,
      doc: "See the `filter` option for offset pagination, this behaves the same."
    ],
    count: [
      type: :boolean,
      doc: "Whether or not to return the page with a full count of all records"
    ]
  ]

  page_opts = @page_opts

  defmodule Opts do
    @moduledoc false

    use Spark.Options.Validator, schema: page_opts
  end

  @doc false
  @spec page_opts() :: page_opts()
  def page_opts do
    @page_opts
  end

  @doc """
  Creates a new `Ash.Page.Keyset.t`.
  """
  @spec new(
          [Ash.Resource.Record.t()],
          non_neg_integer(),
          term(),
          Ash.Query.t(),
          boolean(),
          Keyword.t()
        ) :: t()
  def new(results, count, _sort, original_query, more?, opts) do
    %__MODULE__{
      results: results,
      count: count,
      before: original_query.page[:before],
      after: original_query.page[:after],
      limit: original_query.page[:limit],
      more?: more?,
      rerun: {original_query, opts}
    }
  end

  # A record's keyset is `nil` when its sort values have no JSON form and no signing
  # secret is configured. That's fine for reads that only compute keysets, but a
  # keyset page needs one for every record.
  @doc false
  def ensure_keysets!(results, resource, sort) do
    Enum.each(results, fn
      %{__metadata__: %{keyset: nil}} = record ->
        case encode(record, resource, sort, nil) do
          {:error, {field, type}} ->
            raise ArgumentError, """
            Cannot build a keyset for #{inspect(resource)} sorted by #{inspect(field)}.

            The value of #{inspect(field)} (of type #{inspect(type)}) couldn't be encoded as JSON
            with `Ash.Type.dump_to_embedded/3`. Either make the type's `dump_to_embedded/2`
            return a value that can be encoded as JSON, or set
            `config :ash, :keyset_signing_secret`, which encodes keysets as signed terms.

            See https://hexdocs.pm/ash/pagination.html for more.
            """

          _ ->
            raise ArgumentError, """
            Cannot build a keyset for #{inspect(resource)}, because its sort values couldn't
            be encoded as JSON. Set `config :ash, :keyset_signing_secret`, which encodes
            keysets as signed terms.

            See https://hexdocs.pm/ash/pagination.html for more.
            """
        end

      _ ->
        :ok
    end)
  end

  @doc """
  Appends keyset info to results.
  """
  @spec data_with_keyset([Ash.Resource.Record.t()], term(), term()) :: [Ash.Resource.Record.t()]
  def data_with_keyset(results, resource, sort) when is_list(results) do
    signing_key = signing_key()

    Enum.map(results, fn result ->
      keyset =
        case encode(result, resource, sort, signing_key) do
          {:ok, keyset} -> keyset
          {:error, _} -> nil
        end

      Map.update!(result, :__metadata__, &Map.put(&1, :keyset, keyset))
    end)
  end

  @doc """
  Creates filters on the query using the query for the Keyset.
  """
  @spec filter(Ash.Query.t(), [term()], term(), :after | :before) ::
          {:ok, Keyword.t()} | {:error, term()}
  def filter(%{resource: resource} = query, values, sort, after_or_before)
      when after_or_before in [:after, :before] do
    with {:ok, format, decoded} <- decode_values(values, after_or_before),
         {:ok, zipped} <- zip_fields(sort, decoded, values),
         {:ok, zipped} <- cast_values(zipped, resource, values, format) do
      {:ok, filters(Enum.with_index(zipped), resource, query, after_or_before)}
    else
      {:error, %Ash.Error.Page.InvalidKeyset{} = error} ->
        {:error, maybe_redact(error, resource, sort)}

      {:error, error} ->
        {:error, error}
    end
  end

  # a keyset encodes the sort values of the record it was built from, so it
  # exposes those values to anyone holding it
  defp maybe_redact(error, resource, sort) do
    if Application.get_env(:ash, :redact_sensitive_values_in_errors?, false) and
         sensitive_sort?(resource, sort) do
      %{error | value: Ash.Helpers.redact(error.value)}
    else
      error
    end
  end

  defp sensitive_sort?(resource, sort) do
    Enum.any?(sort, fn
      {%{sensitive?: sensitive?}, _} ->
        sensitive?

      {field, _} ->
        match?(%{sensitive?: true}, Ash.Resource.Info.field(resource, field))
    end)
  end

  defp signing_key do
    case Application.get_env(:ash, :keyset_signing_secret) do
      nil ->
        nil

      secret when is_binary(secret) and secret != "" ->
        secret

      "" ->
        raise ArgumentError,
              "config :ash, :keyset_signing_secret must be a non-empty string or nil, got an empty string"

      _other ->
        raise ArgumentError,
              "config :ash, :keyset_signing_secret must be a non-empty string or nil, got a non-string value"
    end
  end

  defp verify(<<signature::binary-size(32), message::binary>>, signing_key) do
    expected = :crypto.mac(:hmac, :sha256, signing_key, message)

    if :crypto.hash_equals(expected, signature) do
      {:ok, message}
    else
      :error
    end
  end

  defp verify(_bytes, _signing_key), do: :error

  # The signing key is read before the `rescue` below, so that a misconfigured
  # secret raises instead of being reported as an invalid keyset
  defp decode_values(values, key) do
    decode_values(values, key, signing_key())
  end

  defp decode_values(values, key, signing_key) do
    result =
      if signing_key do
        decode_signed_term(values, signing_key)
      else
        decode_json(values)
      end

    case result do
      {:ok, format, decoded} -> {:ok, format, decoded}
      _ -> {:error, Ash.Error.Page.InvalidKeyset.exception(value: values, key: key)}
    end
  rescue
    _e ->
      {:error, Ash.Error.Page.InvalidKeyset.exception(value: values, key: key)}
  end

  # JSON can only decode to plain data, so this never produces a struct, function
  # or atom
  defp decode_json(encoded) do
    with :ok <- check_keyset_size(encoded),
         {:ok, json} <- Base.decode64(encoded),
         {:ok, decoded} when is_list(decoded) <- Jason.decode(json) do
      {:ok, :json, decoded}
    else
      _ -> :error
    end
  end

  # Terms are only ever decoded after their signature has been verified, so they
  # were generated by this application, and their size doesn't need to be limited.
  # The checks after that are defense in depth.
  defp decode_signed_term(encoded, signing_key) do
    with {:ok, bytes} <- Base.decode64(encoded),
         {:ok, message} <- verify(bytes, signing_key),
         :ok <- check_uncompressed(message),
         term <- non_executable_binary_to_term(message, [:safe]),
         :ok <- check_no_expression(term) do
      {:ok, :term, term}
    else
      _ -> :error
    end
  end

  defp check_keyset_size(encoded) do
    if byte_size(encoded) > max_keyset_byte_size() do
      :error
    else
      :ok
    end
  end

  defp max_keyset_byte_size do
    Application.get_env(:ash, :max_keyset_byte_size, @default_max_keyset_byte_size)
  end

  # Ash only ever encodes keysets with uncompressed `:erlang.term_to_binary/1`, so a
  # compressed payload (external term format tag `80`) is never legitimate.
  defp check_uncompressed(<<131, 80, _::binary>>), do: :error
  defp check_uncompressed(_binary), do: :ok

  # A legitimate cursor only ever contains scalar sort values. A decoded term
  # that is or contains an Ash expression (e.g. `%Ash.Query.Call{}`) is a forged
  # cursor attempting to inject a filter expression — which would be spliced into
  # the query as a value and evaluated (SQL injection / RCE depending on the data
  # layer). Reject any such term outright.
  defp check_no_expression(term) do
    if Ash.Expr.expr?(term) do
      :error
    else
      :ok
    end
  end

  defp filters(keyset, resource, query, after_or_before) do
    [or: do_filters(keyset, resource, query, after_or_before)]
  end

  defp do_filters([], _, _, _), do: []

  defp do_filters([{{field, direction, value}, index} | rest], resource, query, after_or_before) do
    {operator, nils_first?} = operator(after_or_before, direction)

    allow_nil? = allow_nil?(resource, field)

    # keyset pagination is generally done like so
    # (x > a) OR
    # (x = a AND y > b) OR
    # (x = a AND y = b AND z > c) OR

    field =
      case field do
        %{__struct__: field_struct} = calc
        when field_struct in [Ash.Query.Calculation, Ash.Query.Aggregate] ->
          calc

        field ->
          Ash.Resource.Info.field(resource, field)
      end

    field =
      if index in query.sort_input_indices do
        %Ash.Query.Ref{attribute: field, relationship_path: [], resource: resource, input?: true}
      else
        %Ash.Query.Ref{attribute: field, relationship_path: [], resource: resource}
      end

    operator_check =
      if is_nil(value) do
        if nils_first? do
          {field, [is_nil: false]}
        else
          {field, [is_nil: true]}
        end
      else
        if nils_first? do
          {field, [{operator, value}]}
        else
          if allow_nil? do
            [or: [{field, [{operator, value}]}, {field, [is_nil: true]}]]
          else
            {field, [{operator, value}]}
          end
        end
      end

    check = [[operator_check]]

    stacked_check =
      if is_nil(value) do
        [[{field, [{:is_nil, true}]}]]
      else
        if nils_first? do
          [[{field, [{:eq, value}]}]]
        else
          if allow_nil? do
            [[[or: [{field, [{:eq, value}]}, {field, [is_nil: true]}]]]]
          else
            [[{field, [{:eq, value}]}]]
          end
        end
      end

    if is_nil(value) and not nils_first? do
      Enum.map(do_filters(rest, resource, query, after_or_before), fn nested ->
        stacked_check ++ nested
      end)
    else
      check ++
        Enum.map(do_filters(rest, resource, query, after_or_before), fn nested ->
          stacked_check ++ nested
        end)
    end
  end

  defp allow_nil?(resource, field) when is_atom(field) do
    case Ash.Resource.Info.field(resource, field) do
      %Ash.Resource.Attribute{allow_nil?: allow_nil?} -> allow_nil?
      %Ash.Resource.Calculation{allow_nil?: allow_nil?} -> allow_nil?
      %Ash.Resource.Aggregate{kind: kind, default: default} -> aggregate_allow_nil?(kind, default)
      _ -> true
    end
  end

  defp allow_nil?(_, %Ash.Query.Calculation{allow_nil?: allow_nil?}), do: allow_nil?

  defp allow_nil?(_, %Ash.Query.Aggregate{kind: kind, default_value: default}),
    do: aggregate_allow_nil?(kind, default)

  defp allow_nil?(_, _), do: true

  # An aggregate can only be `nil` if its kind can produce `nil` and it has no
  # default to use in its place.
  defp aggregate_allow_nil?(kind, _default) when kind in [:count, :exists, :list], do: false
  defp aggregate_allow_nil?(_kind, nil), do: true
  defp aggregate_allow_nil?(_kind, default) when is_function(default), do: true
  defp aggregate_allow_nil?(_kind, _default), do: false

  defp operator(:after, :asc), do: {:gt, false}
  defp operator(:after, :asc_nils_first), do: {:gt, true}
  defp operator(:after, :asc_nils_last), do: {:gt, false}
  defp operator(:after, :desc), do: {:lt, true}
  defp operator(:after, :desc_nils_first), do: {:lt, true}
  defp operator(:after, :desc_nils_last), do: {:lt, false}
  defp operator(:before, :asc), do: {:lt, true}
  defp operator(:before, :asc_nils_first), do: {:lt, false}
  defp operator(:before, :asc_nils_last), do: {:lt, true}
  defp operator(:before, :desc), do: {:gt, false}
  defp operator(:before, :desc_nils_first), do: {:gt, false}
  defp operator(:before, :desc_nils_last), do: {:gt, true}

  defp zip_fields(pkey, values, full_value, acc \\ [])
  defp zip_fields([], [], _full_value, acc), do: {:ok, Enum.reverse(acc)}

  defp zip_fields([{pkey, direction} | rest_pkey], [value | rest_values], full_value, acc) do
    zip_fields(rest_pkey, rest_values, full_value, [{pkey, direction, value} | acc])
  end

  defp zip_fields(_, _, full_value, _),
    do: {:error, Ash.Error.Page.InvalidKeyset.exception(value: full_value)}

  # A keyset only ever encodes scalar sort values. On the way back in we cast each
  # decoded value against the type of the field it sorts on, so a forged cursor
  # whose value can't be a legitimate value of that field (e.g. an injected
  # `%Ash.Query.Call{}` in place of an integer) is rejected here rather than being
  # spliced into the filter and hydrated as an expression. The `expr?` guard in
  # `decode_values/2` covers permissive types (e.g. `:any`) whose `cast_input`
  # would otherwise pass an expression through unchanged.
  defp cast_values(zipped, resource, full_value, format) do
    zipped
    |> Enum.reduce_while({:ok, []}, fn {field, direction, value}, {:ok, acc} ->
      case cast_value(resource, field, value, format) do
        {:ok, value} ->
          {:cont, {:ok, [{field, direction, value} | acc]}}

        :error ->
          {:halt, {:error, Ash.Error.Page.InvalidKeyset.exception(value: full_value)}}
      end
    end)
    |> case do
      {:ok, casted} -> {:ok, Enum.reverse(casted)}
      {:error, error} -> {:error, error}
    end
  end

  # `nil` is inert and is a legitimate keyset value for a nullable sort field.
  defp cast_value(_resource, _field, nil, _format), do: {:ok, nil}

  # Values decoded from JSON are cast the same way as values in a client-supplied
  # filter. A field whose type can't be determined can't be cast, so it's rejected.
  defp cast_value(resource, field, value, :json) do
    case field_type(resource, field) do
      {type, constraints} ->
        case Ash.Type.coerce(type, value, constraints) do
          {:ok, casted} -> {:ok, casted}
          _ -> :error
        end

      :error ->
        :error
    end
  end

  defp cast_value(resource, field, value, :term) do
    case field_type(resource, field) do
      {type, constraints} ->
        case Ash.Type.cast_input(type, value, constraints) do
          {:ok, casted} -> {:ok, casted}
          _ -> :error
        end

      :error ->
        # Field type couldn't be determined; the `expr?` guard has already
        # rejected expressions, so pass the (scalar) value through unchanged.
        {:ok, value}
    end
  end

  defp field_type(resource, field) do
    field
    |> resolve_field(resource)
    |> case do
      # Attributes and calculations carry a resolved type directly. Aggregates
      # may too (query aggregates), so prefer it when present.
      %{type: type, constraints: constraints} when not is_nil(type) ->
        {type, constraints}

      # Resource aggregates generally leave `type`/`constraints` nil — their type
      # is derived from the aggregate kind and the field being aggregated, via the
      # same resolver used everywhere else.
      %struct{} = aggregate when struct in [Ash.Query.Aggregate, Ash.Resource.Aggregate] ->
        case Ash.Query.Aggregate.aggregate_type(resource, aggregate) do
          {:ok, type, constraints} -> {type, constraints}
          _ -> :error
        end

      _ ->
        :error
    end
  end

  defp resolve_field(field, resource) when is_atom(field) or is_binary(field),
    do: Ash.Resource.Info.field(resource, field)

  defp resolve_field(field, _resource), do: field

  # With a signing key, encodes a record's sort values as a signed term. Otherwise
  # encodes them as JSON, if every value can be encoded, or returns the
  # first field whose value doesn't.
  defp encode(record, resource, sort, signing_key) do
    values = field_values(record, sort)

    if signing_key do
      bytes = :erlang.term_to_binary(values)
      {:ok, Base.encode64(:crypto.mac(:hmac, :sha256, signing_key, bytes) <> bytes)}
    else
      with {:ok, json} <- encode_json(resource, sort, values) do
        {:ok, Base.encode64(json)}
      end
    end
  end

  defp encode_json(resource, sort, values) do
    sort
    |> Enum.zip(values)
    |> Enum.reduce_while({:ok, []}, fn {{field, _direction}, value}, {:ok, acc} ->
      case encode_json_value(resource, field, value) do
        {:ok, fragment} -> {:cont, {:ok, [fragment | acc]}}
        :error -> {:halt, {:error, {field_name(field), field_type_name(resource, field)}}}
      end
    end)
    |> case do
      {:ok, fragments} -> Jason.encode(Enum.reverse(fragments))
      {:error, reason} -> {:error, reason}
    end
  end

  # Each value is encoded on its own, so that a value that can't be encoded is
  # attributed to its field, and kept as a fragment that the list is encoded with
  defp encode_json_value(_resource, _field, nil), do: {:ok, nil}

  defp encode_json_value(resource, field, value) do
    with {type, constraints} <- field_type(resource, field),
         {:ok, dumped} <- Ash.Type.dump_to_embedded(type, value, constraints),
         {:ok, json} <- Jason.encode(dumped) do
      {:ok, Jason.Fragment.new(json)}
    else
      _ -> :error
    end
  rescue
    _ -> :error
  end

  defp field_name(%{name: name}), do: name
  defp field_name(field), do: field

  defp field_type_name(resource, field) do
    case field_type(resource, field) do
      {type, _constraints} -> type
      :error -> :unknown
    end
  end

  defp field_values(record, sort) do
    sort
    |> Enum.with_index()
    |> Enum.map(fn
      {{%{__struct__: Ash.Query.Calculation, load: load, name: name}, _}, index} ->
        if load do
          Map.get(record, load)
        else
          # anonymous sort calculations are renamed to `{:__ash_runtime_sort__, index}`
          # when they are computed by `Ash.Actions.Sort.runtime_sort/3`
          case Map.fetch(record.calculations, name) do
            {:ok, value} -> value
            :error -> Map.get(record.calculations, {:__ash_runtime_sort__, index})
          end
        end

      {{%{__struct__: Ash.Query.Aggregate, load: load, name: name}, _}, index} ->
        if load do
          Map.get(record, load)
        else
          case Map.fetch(record.aggregates, name) do
            {:ok, value} -> value
            :error -> Map.get(record.aggregates, {:__ash_runtime_sort__, index})
          end
        end

      {{field, _}, _index} ->
        Map.get(record, field)
    end)
  end

  @doc """
  A restricted version of `:erlang.binary_to_term/2` that forbids
  *executable* terms, such as anonymous functions.
  The `opts` are given to the underlying `:erlang.binary_to_term/2`
  call, with an empty list as a default.
  By default this function does not restrict atoms, as an atom
  interned in one node may not yet have been interned on another
  (except for releases, which preload all code).
  If you want to avoid atoms from being created, then you can pass
  `[:safe]` as options, as that will also enable the safety mechanisms
  from `:erlang.binary_to_term/2` itself.
  Ripped from https://github.com/elixir-plug/plug_crypto/blob/v1.2.0/lib/plug/crypto.ex
  """
  defdelegate non_executable_binary_to_term(binary, opts), to: Ash.Helpers
end
